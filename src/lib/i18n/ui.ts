export const UI: Record<Locale, typeof en> = { en, pt };
export type UiStrings = typeof en;

// Tipos de formação antigos (gravados em português) → chave atual.
const LEGACY_KINDS: Record<string, string> = {
  Graduação: "degree",
  "Pós-graduação": "postgraduate",
  Curso: "course",
  Certificação: "certification",
  Bootcamp: "bootcamp",
};

export function educationKindLabel(kind: string, locale: Locale) {
  const key = LEGACY_KINDS[kind] ?? kind;
  return UI[locale].educationKinds[key] ?? kind;
}
